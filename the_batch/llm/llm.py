"""Provides BatchLLM multimodal RAG model wrapper for text and image retrieval."""

from dataclasses import dataclass, field
from typing import Optional

import numpy as np
import pydantic
from langchain_community.llms.ollama import Ollama
from langchain_core.prompts.prompt import PromptTemplate

from model.rag_llm import OllamaRAGLLM
from schema.documents import ImageDocument
from the_batch.batch_exceptions import (
    BatchLLMAnswerGenerationError,
    BatchLLMInitializationError,
)
from store.vectorstore import VectorStoreI
from internals.dwt import load_signatures
from internals.logger import logger


@dataclass
class BatchLLMResponse:
    """
    DTO representing the response from `BatchLLM`.

    Attributes:
        question: The original user query.
        text_response: The answer generated by the model.
        img_response: A list of `ImageDocument` instances relevant to the query.
    """

    question: str
    text_response: str = field(repr=False)
    img_response: list[ImageDocument] = field(repr=False)


class BatchLLM(pydantic.BaseModel):
    """
    Wrapper for a multimodal RAG model using Ollama.

    This class integrates:
        - An underlying Ollama LLM model.
        - A prompt template to format user queries.
        - A vector store for document retrieval.
        - A retrieval-augmented generation LLM for enhanced querying.

    Attributes:
        model: The underlying language model. Defaults to Llama 3.2.
        prompt_template: Template to format prompts for the model.
        vectorstore: Vector store interface for retrieving relevant documents.
        rag_llm: RAG LLM (automatically initialized if `None`).

    Raises:
        BatchLLMInitializationError: If BatchLLM initialization fails.
    """

    model_config = pydantic.ConfigDict(arbitrary_types_allowed=True)
    model: Ollama = pydantic.Field(default=Ollama(model="llama3.2"))
    vectorstore: VectorStoreI
    prompt_template: PromptTemplate
    rag_llm: Optional[OllamaRAGLLM] = pydantic.Field(default=None)

    def model_post_init(self, context):
        try:
            if not self.rag_llm:
                self.rag_llm = OllamaRAGLLM(
                    model=self.model,
                    vectorstore=self.vectorstore,
                    prompt_template=self.prompt_template,
                )
        except Exception as e:
            raise BatchLLMInitializationError(f"Error while initializing model: {e}")

    def query(self, user_query: str, k: int = 5) -> BatchLLMResponse:
        """
        Process a user query using retrieval augmented generation.

        This method:
            - Queries the RAG LLM to get the text response and relevant documents.
            - Extracts image documents from the retrieved documents.
            - Returns a structured `BatchLLMResponse` containing the question, answer and image documents.

        Args:
            user_query: The input question from the user.
            k: Number of relevant documents to retrieve. Defaults to 5.

        Raises:
            BatchLLMAnswerGenerationError: If `BatchLLM` fails to answer user query.

        Returns:
            BatchLLMResponse: The complete response containing the question,
                                 generated text answer and list of image documents.
        """

        try:
            result = self.rag_llm.query(user_query, k)
            text_response = result.llm_response
            images = [
                document
                for document in result.relevant_docs
                if isinstance(document, ImageDocument)
            ]
            signatures = load_signatures()
            images = self._drop_near_duplicates(images, signatures)
            return BatchLLMResponse(
                question=user_query, text_response=text_response, img_response=images
            )
        except Exception as e:
            raise BatchLLMAnswerGenerationError(
                f"BatchLLM failed to answer user query: {e}"
            )

    def _drop_near_duplicates(
        self,
        candidates: list[ImageDocument],
        signatures: dict[str, np.ndarray],
        threshold: float = 0.95,
    ) -> list[ImageDocument]:
        """
        Drop candidates whose signature is too similar to an already-kept one.

        Args:
            candidates: Retrieved image documents, best first.
            signatures: Image document ID to unit-length wavelet signature.
            threshold: Cosine similarity at or above which two images are duplicates.

        Returns:
            Candidates without near-duplicates, original order preserved.
        """

        kept: list[ImageDocument] = []
        logger.info(f"Size of candidates: {len(candidates)}")  # TODO: remove after testing
        logger.info(f"Candidates ID's: {[cand.id for cand in candidates]}")
        for candidate in candidates:
            candidate_signature = signatures.get(candidate.id)
            if candidate_signature is None:  # nothing to compare against: keep it
                kept.append(candidate)
                continue
            is_duplicate = any(
                signatures[kept_doc.id] @ candidate_signature >= threshold
                for kept_doc in kept
                if kept_doc.id in signatures
            )
            if not is_duplicate:
                kept.append(candidate)
        logger.info(f"Size of kept: {len(kept)}")
        logger.info(f"Kept ID's: {[cand.id for cand in kept]}")
        return kept
