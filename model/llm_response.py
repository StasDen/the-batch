"""Defines the data structure for Retrieval-Augmented Generation (RAG) LLM model responses."""

from dataclasses import dataclass, field

from schema.documents import BaseDocument


@dataclass
class RAGLLMResponse:
    """
    Represents the response returned by a RAG LLM model.

    Attributes:
        user_query: The original user query to the model.
        llm_response: Response generated by the language model.
        relevant_docs : The list of documents retrieved from the vector store
            that were used as context for generating the response.
    """

    user_query: str
    llm_response: str = field(repr=False)
    relevant_docs: list[BaseDocument] = field(repr=False)
